import type { Context } from '@deepseek-ai/cordis'

// ============================================================================
// m01-first-plugin — 你的第一个 Cordis 插件
// ----------------------------------------------------------------------------
// 本课目标：理解 deepseek-harness 的运行时内核——Cordis——最基本的单元「插件」。
// 一个插件就是一个被运行时激活的函数：它接收一个 Context，在里面做事。
//
// 本课不引入任何"AI / Agent"概念，只先建立一个心智模型：
//   harness  = 一棵由「插件」组合而成的树
//   ctx      = 插件被挂载时拿到的那根"树枝"，后续所有能力都挂在这上面
//   cordis.yml = 告诉运行时"要加载哪些插件"的清单
//
// 下一课（m02）会在 ctx 上注册一个"可被撤销"的资源（effect），
// 并在 m03 把它升级成一个 "ctx 上的服务"。本课是后面所有能力生长的起点。
// ============================================================================

// `name` 是可选的插件标识；在你想用 `ctx.plugin(id, ...)` 精确控制挂载时会用到。
// 这里写出来，是为了养成"每个插件都有名字"的好习惯。
export const name = 'first-plugin'

/**
 * apply：插件的入口函数。
 * 运行时（Cordis loader）读到 cordis.yml 里的这个文件后，
 * 会 new 一个 Context 并把它的引用传给 apply。
 *
 * @param ctx 当前这个插件所挂载的上下文（"树枝"）。
 *            后续所有能力（服务、事件、工具、生命周期）都通过这个 ctx 注册。
 */
export function apply(ctx: Context) {
  // 我们先不做任何复杂的事，只打印一行，证明：
  //   "插件被加载了，并且拿到了 ctx"。
  console.log('[first-plugin] 插件已加载，拿到了 ctx，但还没在 ctx 上挂任何东西。')
}
